# Tipos int e float

# in -> Número inteiro
# o tipo representa qualquer número positivo ou negativo.
# um int sem sinal é considerado positivo.
print(11) # int positivo
print(-11) # int negativo
print(0) # int zero

#float -> com ponto flutuante
# o tipo float representa qualquer número com parte decimal.
# Um float sem sinal é considerado positivo

print(1.1, 10.11) # dois floats
print(0.0, -1.5) # float zero e float negativo